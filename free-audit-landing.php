            e.preventDefault();

            // Validate that at least one service checkbox is selected
            const serviceCheckboxes = document.querySelectorAll('input[name="focusArea[]"]:checked');
            if (serviceCheckboxes.length === 0) {
                alert('Please select at least one service you are interested in.');
                return false;
            }

            // Track conversion event
            if (typeof gtag !== 'undefined') {
                gtag('event', 'conversion', {
                    'send_to': 'AW-XXXXXXXXX/XXXXXX', // Replace with your conversion ID
                    'event_callback': function() {
                        console.log('Conversion tracked');
                    }
                });
            }

            // Track Meta Pixel event
            if (typeof fbq !== 'undefined') {
                fbq('track', 'Lead');
            }

            // Submit form
            const formData = new FormData(this);

            fetch('process-audit-form.php', {
                method: 'POST',
                body: formData
            })
            .then(response => response.json())
            .then(data => {
                if (data.success) {
                    window.location.href = 'audit-thank-you.php';
                } else {
                    alert('There was an error submitting your form. Please try again.');
                }
            })
            .catch(error => {
                console.error('Error:', error);
                alert('There was an error submitting your form. Please try again.');
            });
        });

        // Intersection Observer for animations
        const observerOptions = {
            threshold: 0.1,
            rootMargin: '0px 0px -50px 0px'
        };

        const observer = new IntersectionObserver(function(entries) {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.style.opacity = '1';
                    entry.target.style.transform = 'translateY(0)';
                }
            });
        }, observerOptions);

        document.querySelectorAll('.fadeInUp').forEach(el => {
            el.style.opacity = '0';
            el.style.transform = 'translateY(30px)';
            el.style.transition = 'all 0.6s ease';
            observer.observe(el);
        });

        // Show/hide sticky CTA based on scroll
        let lastScroll = 0;
        window.addEventListener('scroll', function() {
            const currentScroll = window.pageYOffset;
            const stickyCTA = document.querySelector('.sticky-cta');

            if (currentScroll > 500) {
                stickyCTA.style.transform = 'translateY(0)';
            } else {
                stickyCTA.style.transform = 'translateY(100%)';
            }

            lastScroll = currentScroll;
        });
